"""Step 8: apply the pre-registered score (docs/scoring.md) to the Step 7 feature rows and write the results.

Run from the repo root:  PYTHONPATH=src .venv/bin/python scripts/run_scoring.py
Inputs (no new data, no model calls): docs/scoring.md (config), data/processed/features.json,
data/processed/llm_signals_sonnet.json + data/cases/gold_signals.json (Step 6 match -> gold-confirmed ids),
registry_signals.json (late clues only).
Outputs: data/processed/scores.json, docs/scoring_results.md.
"""

import json
from collections import Counter
from pathlib import Path

from deal_radar.cases import load_cases
from deal_radar.extract import match
from deal_radar.features import late_clues, load_json_list
from deal_radar.schemas import Signal
from deal_radar.score import (
    TERMS,
    VARIANTS,
    band,
    compare_pairs,
    confidence,
    contributions,
    hypothesis_verdicts,
    load_config,
    score,
)

ROOT = Path(__file__).resolve().parents[1]
PROCESSED = ROOT / "data" / "processed"
CASES = ROOT / "data" / "cases"
PE_PAIRS = {"P1", "P6"}
PROXY = {"ptsg", "xeinadin"}  # sponsor entry = announcement, completion not confirmed


def confirmed_signal_ids() -> set[str]:
    """Sonnet signals that matched a gold label in the Step 6 evaluation (same extract.match)."""
    gold = json.loads((CASES / "gold_signals.json").read_text())["signals"]
    sonnet = load_json_list(PROCESSED / "llm_signals_sonnet.json", Signal)
    return {p.signal_id for _, p in match(gold, sonnet)["pairs"]}


def main() -> None:
    config = load_config((ROOT / "docs" / "scoring.md").read_text())
    rows = json.loads((PROCESSED / "features.json").read_text())
    confirmed = confirmed_signal_ids()
    out = []
    for r in rows:
        total, contribs = score(r, config, confirmed)
        out.append({k: r[k] for k in ("company_id", "pair_id", "role", "prediction_date", "horizon", "label")}
                   | {"score": total, "band": band(total, config), "confidence": confidence(r, config),
                      "contributions": contribs,
                      "variant_scores": {v: score(r, config, confirmed, v)[0] for v in VARIANTS if v != "full"}})
    (PROCESSED / "scores.json").write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n")
    comparisons = {v: compare_pairs(rows, config, confirmed, v) for v in VARIANTS}
    _, _, pairs = load_cases(CASES)
    signals = load_json_list(PROCESSED / "llm_signals_sonnet.json", Signal) + \
        load_json_list(PROCESSED / "registry_signals.json", Signal)
    clues = {p.pair_id: late_clues(p, signals) for p in pairs}
    (ROOT / "docs" / "scoring_results.md").write_text(render(rows, out, comparisons, config, confirmed, pairs, clues))
    for v in VARIANTS:
        print(v, dict(Counter(c["outcome"] for c in comparisons[v])))


def fmt(x: float) -> str:
    return f"{x:.2f}"


def term_diffs(deal_row, control_row, config, confirmed) -> dict:
    d = {c["term"]: c["value"] for c in contributions(deal_row, config, confirmed)}
    k = {c["term"]: c["value"] for c in contributions(control_row, config, confirmed)}
    return {t: round(d.get(t, 0) - k.get(t, 0), 6) for t in TERMS if abs(d.get(t, 0) - k.get(t, 0)) > 1e-9}


def render(rows, out, comparisons, config, confirmed, pairs, clues) -> str:
    row_of = {(r["pair_id"], r["horizon"], r["role"]): r for r in rows}
    cmp_of = {v: {(c["pair_id"], c["horizon"]): c for c in comparisons[v]} for v in VARIANTS}
    L = ["# Scoring results (Step 8)", "",
         "Generated by `scripts/run_scoring.py` from the pre-registered rules in `docs/scoring.md` (commits bb19cdc and "
         "ecf3b3b). Do not edit by hand.", "",
         "**Read this first.** Six matched pairs, 18 deal-vs-control comparisons of correlated snapshots: a feasibility "
         "study (PRD §17). Any separation below is **hypothesis-generating, not validation**, and nothing here is a "
         "claim of predictive performance. The score is a ranking aid, never a probability. PTSG and Xeinadin holding "
         "periods are an **announcement-based proxy** (sponsor entry = announcement, completion not confirmed).", "",
         "## Per pair: deal vs control (deal score – control score, outcome)", "",
         "Variants: **full** (pre-registered weights); **holding-only** (clock term alone = benchmark b, and the "
         "clock-only ablation); **full − clock**; **sensitivity** (all weights ±1, clock = min(years/5, 1)); "
         "**verified-only** (diagnostic: LLM terms with no gold-matched signal removed). Benchmark (a), random: 9 of "
         "18 wins expected.", ""]
    for p in pairs:
        L += [f"### {p.pair_id}: {p.deal_company_id} (deal) vs {p.control_company_id} (control), anchor {p.anchor_date}"
              + (" — PE-backed pair" if p.pair_id in PE_PAIRS else " — VC-backed pair"), "",
              "| Horizon | Full | Holding-only | Full − clock | Sensitivity | Verified-only | Deal band / confidence | Control band / confidence |",
              "|---|---|---|---|---|---|---|---|"]
        for h in ("12m", "6m", "3m"):
            cells = [f"{fmt(cmp_of[v][(p.pair_id, h)]['deal_score'])} – {fmt(cmp_of[v][(p.pair_id, h)]['control_score'])} "
                     f"**{cmp_of[v][(p.pair_id, h)]['outcome']}**" for v in VARIANTS]
            so = {(s["pair_id"], s["horizon"], s["role"]): s for s in out}
            d, k = so[(p.pair_id, h, "deal")], so[(p.pair_id, h, "control")]
            L.append(f"| {h} | " + " | ".join(cells) + f" | {d['band']} / {d['confidence']} | {k['band']} / {k['confidence']} |")
        L.append("")
    L += ["### Outcome counts per variant (shown only alongside the per-pair tables; never a pooled accuracy)", "",
          "| Variant | Wins | Ties | Losses |", "|---|---|---|---|", "| Random (benchmark a), expected | 9 | — | — |"]
    for v in VARIANTS:
        c = Counter(x["outcome"] for x in comparisons[v])
        L.append(f"| {v} | {c['win']} | {c['tie']} | {c['loss']} |")

    L += ["", "## Where the full score disagrees with holding-only", ""]
    dis = [(c, cmp_of["holding_only"][(c["pair_id"], c["horizon"])]) for c in comparisons["full"]
           if c["outcome"] != cmp_of["holding_only"][(c["pair_id"], c["horizon"])]["outcome"]]
    for c, h in dis:
        diffs = term_diffs(row_of[(c["pair_id"], c["horizon"], "deal")], row_of[(c["pair_id"], c["horizon"], "control")],
                           config, confirmed)
        cause = ", ".join(f"{t} {v:+.2f}" for t, v in diffs.items() if t != "clock") or "none"
        L.append(f"- {c['pair_id']} {c['horizon']}: holding-only **{h['outcome']}** → full **{c['outcome']}**. "
                 f"Non-clock terms (deal − control): {cause}.")
    if not dis:
        L.append("- none")

    L += ["", "## Wins that depend on unconfirmed extraction", "",
          "Full-score wins that are not wins under verified-only (LLM terms whose signals did not match gold removed).", ""]
    flips = [c for c in comparisons["full"] if c["outcome"] == "win"
             and cmp_of["verified_only"][(c["pair_id"], c["horizon"])]["outcome"] != "win"]
    for c in flips:
        v = cmp_of["verified_only"][(c["pair_id"], c["horizon"])]
        dead = [x for x in contributions(row_of[(c["pair_id"], c["horizon"], "deal")], config, confirmed)
                + contributions(row_of[(c["pair_id"], c["horizon"], "control")], config, confirmed)
                if x["gold_confirmed"] is False]
        L.append(f"- {c['pair_id']} {c['horizon']}: full win ({fmt(c['deal_score'])} – {fmt(c['control_score'])}) → "
                 f"verified-only **{v['outcome']}** ({fmt(v['deal_score'])} – {fmt(v['control_score'])}). Unconfirmed: "
                 + "; ".join(f"{x['term']} via {', '.join(x['ids'])}" for x in dead) + ".")
    if not flips:
        L.append("- none")

    L += ["", "## Why: contributions per company and horizon (full score)", "",
          "Each term with its Step 7 provenance ids and gold_confirmed flag (true/false for LLM terms; n/a for "
          "registry and sponsor-entry terms).", ""]
    for s in out:
        terms = sorted(s["contributions"], key=lambda c: -abs(c["value"]))
        why = "; ".join(f"{c['term']} {c['value']:+.2f} [{', '.join(c['ids'])}] (gold_confirmed {str(c['gold_confirmed']).lower()})"
                        for c in terms) or "no scoring terms"
        tag = " (holding = announcement-based proxy)" if s["company_id"] in PROXY else ""
        L.append(f"- **{s['company_id']}** {s['horizon']} ({s['prediction_date']}): score {fmt(s['score'])}, "
                 f"{s['band']} / confidence {s['confidence']}{tag}. {why}")

    L += ["", "## Hypotheses (against the pre-registered criteria in docs/scoring.md §5)", ""]
    v = hypothesis_verdicts(rows, comparisons, [p.pair_id for p in pairs], PE_PAIRS)
    h1, h2, h3 = v["H1"], v["H2"], v["H3"]
    L += ["### H1: clock + intent beats either alone and beats holding-only", "",
          ("**Untestable** on this sample: `intent_present` is False in all 36 rows." if not h1["testable"] else
           f"Testable: intent present in {h1['intent_rows']} rows (see table).")]
    h2b = ("PE advantage rests on clock-driven/other wins" if h2["labelled_pe_advantage"]
           else "no PE advantage once weak and unconfirmed-only wins are set aside")
    L += ["", "### H2: PE-backed companies are the most predictable segment", "",
          f"- **(a) Simple verdict: {h2['simple']}.** Full-score wins: PE pairs {h2['wins']['PE']} of {h2['n']['PE']} comparisons; "
          f"VC pairs {h2['wins']['VC']} of {h2['n']['VC']}.",
          f"- **(b) Labelled breakdown:** PE wins by category {h2['categories']['PE']}; VC wins by category {h2['categories']['VC']}. "
          f"Counting only clock-driven and other wins: PE {h2['supportive']['PE']}/{h2['n']['PE']}, VC {h2['supportive']['VC']}/{h2['n']['VC']}: {h2b}.",
          "- Carve-outs: **untestable** (none in the sample). Two PE pairs are anecdotal; hypothesis-generating, not validation."]
    if (h2["simple"] == "not contradicted") != h2["labelled_pe_advantage"]:
        L.append("- (a) and (b) disagree: the simple verdict counts every win, while the breakdown discounts weak "
                 "(debt-only) and unconfirmed-only wins.")
    counts = h3["counts"]
    L += ["", "### H3: useful signals appear at least 6 months before the announcement", "",
          f"- **(a) Simple verdict:** {h3['n_simple']} of 6 pairs support it (a full-score deal win at 12m or 6m not resting "
          f"solely on gold-unconfirmed terms); {'not contradicted' if h3['n_simple'] else 'contradicted'} on this sample.",
          f"- **(b) Labelled breakdown:** clock-driven {counts['clock-driven']}, other (named) {counts['other']}, "
          f"weak (debt-only) {counts['weak (debt-only)']}, no support {counts['no support']}; "
          f"{'not contradicted' if counts['clock-driven'] + counts['other'] else 'contradicted'} on this sample.", "",
          "| Pair | (a) support | (b) category | Strongest early win (horizon: drivers) |", "|---|---|---|---|"]
    for pid, x in h3["per_pair"].items():
        best = x["best"]
        support = ("yes (technically supported, fragile)" if x["fragile"] else "yes") if x["simple"] else "no"
        L.append(f"| {pid} | {support} | {x['label']} | "
                 f"{best['horizon'] + ': ' + ', '.join(best['drivers']) if best else '—'} |")
    if h3["disagree"]:
        L.append("")
        L.append(f"- (a) and (b) disagree for {', '.join(h3['disagree'])}: the early win is weak (debt-only), which "
                 "(a) counts as support and (b) does not, because debt events do not separate deals from controls "
                 "elsewhere in this sample.")
    for pid in sorted(p for p, x in h3["per_pair"].items() if x["fragile"]):
        best = h3["per_pair"][pid]["best"]
        L.append(f"- **{pid}: technically supported, fragile.** Its supporting {best['horizon']} win meets the "
                 f"pre-registered rule ({best['category']}: {', '.join(best['drivers'])}; not solely gold-unconfirmed "
                 "terms), but it is **not a win under verified-only**: it needs a gold-unconfirmed LLM term (see "
                 "'Wins that depend on unconfirmed extraction').")
    L += ["- Late clues (below) count against H3, never for it.", "",
          "## Late clues (Step 7; shown separately, never scored)", "",
          "| Pair | Company | Type | Status | Published |", "|---|---|---|---|---|"]
    for p in pairs:
        for s in sorted(clues[p.pair_id], key=lambda s: (s.publication_date, s.company_id)):
            L.append(f"| {p.pair_id} | {s.company_id} | {s.signal_type} | {s.status} | {s.publication_date} |")
    L += ["", "## Limitations", "",
          "- Six pairs, 18 correlated comparisons; results are per pair and hypothesis-generating, not validation.",
          "- Weights were written after the Step 7 feature table had been seen (disclosed in docs/scoring.md); the "
          "sensitivity and verified-only variants show how much results depend on that.",
          "- No snapshot has an intent signal, so the strongest PRD signal class contributes nothing; H1 is untestable.",
          "- Two of four PE holding clocks are announcement-based proxies (PTSG, Xeinadin).",
          "- The 5-year clock cap is an assumption about a typical PE hold, not a fact.",
          "- Debt events are frequent at controls too; wins resting only on them are labelled weak.",
          "- LLM readiness/fundraise terms inherit Step 6 extraction errors; see the verified-only column.",
          "- No PE fund age, no sector context, no fundraise size threshold (Step 7 limitations).",
          "- Confidence is reported separately and never changes the score; insufficient evidence is not low likelihood."]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    main()
