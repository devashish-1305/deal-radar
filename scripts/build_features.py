"""Step 7: build point-in-time feature rows (6 pairs x 2 companies x 3 snapshot dates) and docs/features.md.

Run from the repo root:  PYTHONPATH=src .venv/bin/python scripts/build_features.py
Inputs (existing files only; no searches, no LLM calls): data/cases/*.json, data/processed/evidence.json,
registry_events.json, registry_signals.json, llm_signals_sonnet.json.
Outputs: data/processed/features.json, docs/features.md.
"""

import json
from pathlib import Path

from deal_radar.cases import load_cases
from deal_radar.features import (
    HOLDING_BASIS,
    build_rows,
    late_clues,
    load_json_list,
    load_sponsor_entries,
)
from deal_radar.schemas import Evidence, RegistryEvent, Signal

ROOT = Path(__file__).resolve().parents[1]
CASES = ROOT / "data" / "cases"
PROCESSED = ROOT / "data" / "processed"


def load_inputs():
    companies, transactions, pairs = load_cases(CASES)
    evidence = load_json_list(PROCESSED / "evidence.json", Evidence)
    events = [RegistryEvent.model_validate(e) for e in json.loads((PROCESSED / "registry_events.json").read_text())["events"]]
    llm = load_json_list(PROCESSED / "llm_signals_sonnet.json", Signal)
    registry_signals = load_json_list(PROCESSED / "registry_signals.json", Signal)
    owner = {c.company_id: c.owner_type for c in companies}
    sponsors = load_sponsor_entries(CASES / "sponsor_entry.json", evidence, events, pairs,
                                    {c for c, o in owner.items() if o == "pe_backed"})
    outcome_ids = {o["event_id"] for o in json.loads((CASES / "outcome_events.json").read_text())}
    return companies, transactions, pairs, evidence, events, llm, registry_signals, owner, sponsors, outcome_ids


def main() -> None:
    companies, transactions, pairs, evidence, events, llm, registry_signals, owner, sponsors, outcome_ids = load_inputs()
    rows = build_rows(pairs, transactions, owner, sponsors, evidence, events, llm, outcome_ids)
    (PROCESSED / "features.json").write_text(json.dumps(rows, indent=1, ensure_ascii=False) + "\n")
    clues = {p.pair_id: late_clues(p, llm + registry_signals) for p in pairs}
    (ROOT / "docs" / "features.md").write_text(render(rows, pairs, sponsors, clues))
    print(f"{len(rows)} rows; late clues: { {k: len(v) for k, v in clues.items()} }")


def yn(v):
    return "yes" if v else "no"


def render(rows, pairs, sponsors, clues) -> str:
    L = ["# Point-in-time features (Step 7)", "",
         "Generated by `scripts/build_features.py`. Do not edit by hand. No scoring here.", "",
         "Each row is one company at one prediction date (12, 6 and 3 months before its pair's anchor). **Only items "
         "published strictly before the prediction date are used** (publication date gates usability; it never "
         "replaces an event or entry date). Every feature lists the ids it used in `data/processed/features.json` "
         "(`provenance`).", "",
         "## Feature definitions", "",
         "| Feature | Plain-English meaning | Source |", "|---|---|---|",
         "| pe_holding_years | Years since the current PE sponsor's entry (PE-backed only; otherwise empty). | `data/cases/sponsor_entry.json` only |",
         "| holding_basis | How the entry date is established: `psc_notified` (Companies House PSC notified date, control began) or `announced_proxy` (deal announcement date; completion not confirmed). **`announced_proxy` clocks are proxy-based, not a confirmed ownership entry.** | sponsor entry |",
         "| recently_acquired | The sponsor entered within the 24 months before the prediction date (PRD counter-signal, <2 years). Shares holding_basis. LLM `recently_acquired` signals are ignored. | sponsor entry |",
         "| debt_event_12m / debt_financings_12m | Any / number of charges created or satisfied, filed in the 12 months before the prediction date (de-duplicated, see below). | Companies House charges |",
         "| intent_present | Any confirmed or attributed direct-intent signal (advisers appointed, strategic review, exploring options, parent non-core). Speculative excluded. | LLM (Sonnet 5.5) |",
         "| readiness_18m (+ readiness_date_basis) | Any new CFO/chair or governance change that happened in the 18 months before the prediction date, by event date; if the article gives no event date, its publication date is used and flagged `publication_proxy`. | LLM (Sonnet 5.5) |",
         "| fundraise_12m (+ fundraise_date_basis) | Any equity round in the 12 months before the prediction date, by event date (publication date as a flagged `publication_proxy` if no event date). Recency only: PRD §8 defines no size threshold. | LLM (Sonnet 5.5) |",
         "| coverage_items | Number of usable evidence items plus usable registry events (how much we know, not a signal). | evidence + registry |", "",
         "Rules (from PRD definitions only, never from gold disagreements): external_context never contributes; "
         "only the sponsor entry sets the holding clock, so an undated (or any) LLM `pe_holding_period` never does; "
         "the deal's own ownership change (`data/cases/outcome_events.json`) is never used.", "",
         "## Sponsor entries (PE-backed companies)", "",
         "| Company | Sponsor | Announced | Entry date | Entry basis → holding_basis | Source | Published | Note |",
         "|---|---|---|---|---|---|---|---|"]
    for cid, s in sponsors.items():
        L.append(f"| {cid} | {s.sponsor} | {s.announced_date or '—'} | {s.entry_date} | {s.entry_basis} → "
                 f"`{HOLDING_BASIS[s.entry_basis]}` | {s.source_kind} `{s.source_id}` | {s.publication_date} | {s.note} |")
    L += ["", "## Per pair: deal vs control at 12 / 6 / 3 months", ""]
    for p in pairs:
        L += [f"### {p.pair_id} (anchor {p.anchor_date})", "",
              "| Company (role) | Horizon | Prediction date | Label | Holding years (basis) | Recently acquired | Debt 12m (n) | Intent | Readiness 18m | Fundraise 12m | Coverage |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in (r for r in rows if r["pair_id"] == p.pair_id):
            f = r["features"]
            hold = f"{f['pe_holding_years']} ({f['holding_basis']})" if f["pe_holding_years"] is not None else "—"
            ready = yn(f["readiness_18m"]) + (f" ({f['readiness_date_basis']})" if f["readiness_date_basis"] == "publication_proxy" else "")
            fund = yn(f["fundraise_12m"]) + (f" ({f['fundraise_date_basis']})" if f["fundraise_date_basis"] == "publication_proxy" else "")
            L.append(f"| {r['company_id']} ({r['role']}) | {r['horizon']} | {r['prediction_date']} | {r['label']} | {hold} | "
                     f"{yn(f['recently_acquired'])} | {yn(f['debt_event_12m'])} ({f['debt_financings_12m']}) | "
                     f"{yn(f['intent_present'])} | {ready} | {fund} | {f['coverage_items']} |")
        L.append("")
    L += ["## Late clues (reporting only, never features)", "",
          "Signals published in [3-month snapshot date, anchor), i.e. the last 3 months before the deal date. They test "
          "H3 (lead time) and are excluded from every feature row by construction.", "",
          "| Pair | Company | Type | Status | Event date | Published | Source |", "|---|---|---|---|---|---|---|"]
    any_clue = False
    for p in pairs:
        for s in sorted(clues[p.pair_id], key=lambda s: (s.publication_date, s.company_id)):
            any_clue = True
            L.append(f"| {p.pair_id} | {s.company_id} | {s.signal_type} | {s.status} | {s.event_date or '—'} | "
                     f"{s.publication_date} | {s.source_url} |")
    if not any_clue:
        L.append("| — | — | — | — | — | — | — |")
    L += ["", "## De-duplication key (debt)", "",
          "Charge events carry `charge_code` and `lenders`. Key = (event_type, event_date, sorted lenders). Within one "
          "entity, distinct charges are never merged (two separate charges with the same type, date and lender at one "
          "entity count twice). Across group entities, events merge only if type, date and lenders all match (the same "
          "financing registered at several entities counts once). An event with no lenders is never merged.", "",
          "## Proxy rules", "",
          "- `fundraise_date_basis` / `readiness_date_basis` = `publication_proxy` when the article gives no event date "
          "and its publication date is used to judge recency.",
          "- `holding_basis` = `announced_proxy` when the sponsor entry is an announcement whose completion the source "
          "does not confirm (PTSG, Xeinadin). No completion dates are invented.", "",
          "## Limitations", "",
          "- **PE fund age:** no data source in the pilot; no feature.",
          "- **Sector context:** external_context signals are excluded (PRD §8: context only); no sector feature.",
          "- **Fundraise size:** PRD §8 defines no 'large' threshold; fundraise_12m is recency only.",
          "- **Sparse intent:** direct-intent evidence is rare; at every snapshot `intent_present` depends on a handful "
          "of articles, and missing evidence is never treated as absence of a signal.",
          "- **Readiness from the LLM includes the Cytora advisory-board signal** (a gold false positive); it is kept "
          "because Step 7 rules come from PRD definitions only, not from gold disagreements.",
          "- **CFO/chair from the registry:** Companies House gives no occupation data, so readiness comes from articles only.",
          "- **Proxy clocks:** PTSG and Xeinadin holding clocks start at announcement dates (`announced_proxy`).",
          "- Six pairs, 36 rows: a feasibility study, not a validation sample."]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    main()
